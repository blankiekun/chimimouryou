const E = L.engine({
    name: 'Monochrome',
    check: () => L.SearchStringFileInfo('PANDA HOUSE') && L.SearchStringFileInfo('Monochrome'),
    attach() {
        if (h1()) return true;
        // https://vndb.org/v11759
        // ラブレッスン
        let addr = L.findiatcallormov(L.FindFunction('GetTextExtentPoint32A'), L.processStartAddress, L.processStartAddress, L.processStopAddress);
        if (!addr) return false;
        addr = L.findEnclosingAlignedFunction(addr, 0x100);
        if (!addr) return false;
        let last = ''; // static std::string last
        return L.NewHook({
            address: addr,
            offset: L.regoffset('edx'),
            type: L.USING_STRING,
            filter_fun(buffer) {
                const s = buffer.strA();
                if (s === last) buffer.clear();
                last = s;
            },
        }, 'Monochrome');
    },
});

module.exports = E;
if (!module.parent) L.run(E);
